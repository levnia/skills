#!/usr/bin/env node
// tokens-css.mjs — 把 token 輸出成「不依賴 Tailwind、不依賴 .dark class」的獨立 CSS（零依賴）。
// 給載入不了 app CSS 的頁面用：伺服器直接送出的錯誤頁、注入到第三方頁面的小元件。
//
// 用法：node tokens-css.mjs <tokens.css> [<皮膚覆寫.css> ...] [--only primary,background,...]
//   - 依序讀入每個檔案的 :root 與 .dark 區塊，後面的檔案逐一覆寫前面的同名 token
//   - 輸出 :root（亮色）與 @media (prefers-color-scheme: dark) { :root }（暗色）兩組變數
//   - 只輸出、不新增：token 名稱與輸入完全相同（名稱是契約）
//   - --only 只保留列出的 token；列了不存在的名稱會直接失敗（exit 2），避免拼錯後靜默少一個變數
// 輸出到 stdout，請自行導向檔案，例如：> src/tokens.generated.css

import { readFileSync, realpathSync } from "node:fs";
import { fileURLToPath } from "node:url";

// 讀出一段 CSS 中所有頂層 :root 與 .dark 區塊的 token（--name: value）
export function readBlocks(css) {
  const text = css.replace(/\/\*[\s\S]*?\*\//g, "");
  const light = {};
  const dark = {};
  for (const m of text.matchAll(/(?:^|[}\s;])(:root|\.dark)\s*\{([^{}]*)\}/g)) {
    const target = m[1] === ":root" ? light : dark;
    for (const d of m[2].matchAll(/--([\w-]+)\s*:\s*([^;]+?)\s*(?:;|$)/g)) target[d[1]] = d[2];
  }
  return { light, dark };
}

export function buildTokensCss(sources, { only } = {}) {
  const light = {};
  const dark = {};
  for (const css of sources) {
    const b = readBlocks(css);
    Object.assign(light, b.light);
    Object.assign(dark, b.dark);
  }
  if (only) {
    for (const name of only) {
      if (!(name in light) && !(name in dark)) throw new Error(`unknown token: ${name}`);
    }
  }
  const pick = (obj) => Object.entries(obj).filter(([k]) => !only || only.includes(k));
  const lines = (obj, indent) => pick(obj).map(([k, v]) => `${indent}--${k}: ${v};`).join("\n");
  let out = `:root {\n${lines(light, "  ")}\n}\n`;
  if (pick(dark).length) {
    out += `@media (prefers-color-scheme: dark) {\n  :root {\n${lines(dark, "    ")}\n  }\n}\n`;
  }
  return out;
}

const invokedDirectly = (() => {
  try {
    return process.argv[1] && realpathSync(fileURLToPath(import.meta.url)) === realpathSync(process.argv[1]);
  } catch {
    return false;
  }
})();

if (invokedDirectly) {
  const args = process.argv.slice(2);
  const i = args.indexOf("--only");
  const only = i >= 0 ? (args[i + 1] ?? "").split(",").map((s) => s.trim()).filter(Boolean) : undefined;
  const files = args.filter((_, j) => i < 0 || (j !== i && j !== i + 1));
  if (!files.length || (i >= 0 && !only.length)) {
    console.error("usage: node tokens-css.mjs <tokens.css> [<override.css> ...] [--only a,b,c]");
    process.exit(2);
  }
  try {
    const css = buildTokensCss(files.map((f) => readFileSync(f, "utf8")), { only });
    process.stdout.write(`/* generated by fleet-ui scripts/tokens-css.mjs from ${files.join(", ")} — do not edit */\n${css}`);
  } catch (e) {
    console.error(e.message);
    process.exit(2);
  }
}
